// BLACKICE's reproducible, offline import of the pinned Apache-2.0 Catalyst
// methods. Only the catalog's declarative dependency graph is evaluated, in a
// bounded VM without host APIs. The application consumes the resulting JSON.
// Usage: node --experimental-vm-modules scripts/import-catalyst-catalog.mjs
//        --source /path/to/pinned/catalyst --write
//        --check (defaults to the bundled, exact upstream source snapshot)
import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import vm from 'node:vm';

export const CATALYST_SOURCE = Object.freeze({
  project: 'Catalyst', repository: 'https://github.com/MoonlightClarity/Catalyst',
  commit: '1c50eea56ea4c05de8055084583145882dc8d302', license: 'Apache-2.0',
  retrievalManifestSha256: 'beca57f6e36fdd97378ef287e3b9977ea485fa2948b68367ffe871d308a137dc',
  fileCount: 39,
});
export const CATALYST_VENDOR_DIR = fileURLToPath(new URL('../lib/vendor/catalyst/', import.meta.url));
export const CATALYST_NOTICE = `# Catalyst catalog attribution\n\nThis directory contains method definitions and discovery metadata from [Catalyst](${CATALYST_SOURCE.repository}), pinned at commit \`${CATALYST_SOURCE.commit}\`. Catalyst is licensed under the Apache License 2.0; the complete upstream license is preserved in \`LICENSE.txt\`. The upstream licensing inventory is preserved in \`LICENSES.md\`.\n\nThe 39 files under \`upstream/\` are an unchanged source snapshot. Each file is bound to its original path, byte length and SHA-256 digest in \`retrieval-manifest.json\`. The materialized \`catalog.json\` retains 581 complete definitions, 2,906 original steps, discovery metadata, source references, source IDs, and per-definition digests. It is generated from the pinned TypeScript definitions without changing their prompts or reference URLs.\n\nBLACKICE changes the presentation and execution integration in \`lib/catalyst-methods.mjs\`: stable BLACKICE IDs, existing task and step types, artifact-oriented instructions, expected results, checks, fallback prerequisites, usage cautions, output discovery metadata, and relationships resolved to method IDs. The original Catalyst definitions and metadata remain separately inspectable in this directory. These adaptations are authored for BLACKICE; they are not an upstream Catalyst release or a claim of independent methodological validation.\n\nThe catalog is a set of reusable methods. Reference links are retained upstream references, not a claim that every link was visited or its content independently verified for this BLACKICE release. The retained source license covers the imported Catalyst code and definitions; external referenced works retain their own terms.\n\n## Reproduce the import\n\nFrom the BLACKICE source root, run:\n\n\`\`\`sh\nnode --experimental-vm-modules scripts/import-catalyst-catalog.mjs --check\n\`\`\`\n\nThis offline maintainer check verifies all source hashes, evaluates only the catalog's declarative module graph in a bounded VM without host APIs, and compares every generated byte with the bundled output. BLACKICE itself loads only the generated JSON and never evaluates upstream TypeScript.\n\nTo regenerate the exact reviewed snapshot after checking out the pinned source, use the same command with \`--source /path/to/pinned/source --write\`. That source directory must contain the exact retrieval manifest and all 39 bound source files. A newer upstream commit requires explicit source review and an updated pin.\n`;
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const fail = message => { throw new Error(`Catalyst import: ${message}`); };
const normalFile = async file => {
  const info = await lstat(file);
  if (!info.isFile() || info.isSymbolicLink() || info.size > 2 * 1024 * 1024) fail(`expected a bounded ordinary file: ${file}`);
  return readFile(file);
};

export async function readPinnedCatalystSource(directory) {
  const manifestBytes = await normalFile(path.join(directory, 'retrieval-manifest.json'));
  if (hash(manifestBytes) !== CATALYST_SOURCE.retrievalManifestSha256) fail('the retrieval manifest does not match the pinned source revision.');
  const manifest = JSON.parse(manifestBytes);
  if (manifest.repository !== CATALYST_SOURCE.repository || manifest.commit !== CATALYST_SOURCE.commit || manifest.files.length !== CATALYST_SOURCE.fileCount) fail('the source identity or file count changed.');
  const files = new Map();
  for (const entry of manifest.files) {
    if (typeof entry.path !== 'string' || entry.path.includes('\\') || !/^(?:LICENSE(?:S\.md|\.txt)|docs\/[a-z0-9-]+\.md|src\/domain\/[A-Za-z]+\.ts)$/.test(entry.path) || files.has(entry.path)) fail('the manifest contains an unexpected or duplicate source path.');
    const bytes = await normalFile(path.join(directory, ...entry.path.split('/')));
    if (bytes.length !== entry.bytes || hash(bytes) !== entry.sha256) fail(`source bytes changed: ${entry.path}`);
    files.set(entry.path, bytes);
  }
  return { manifest, manifestBytes, files };
}

export async function materializeCatalystCatalog(pinned) {
  if (typeof vm.SourceTextModule !== 'function') fail('run this maintainer command with node --experimental-vm-modules.');
  const context = vm.createContext(Object.create(null), { codeGeneration: { strings: false, wasm: false } }), modules = new Map();
  const workflowPaths = [...pinned.files.keys()].filter(file => /^src\/domain\/techniquesCatalogWorkflows[A-Za-z]*\.ts$/.test(file));
  const imports = workflowPaths.map((file, index) => `import * as workflow${index} from ${JSON.stringify(`./${file}`)};`).join('\n');
  const rootSource = `
    import { BUILT_IN_TECHNIQUES } from './src/domain/techniques.ts';
    import { EXTENDED_BUILT_IN_TECHNIQUES } from './src/domain/techniquesExtended.ts';
    import { INTERDISCIPLINARY_BUILT_IN_TECHNIQUES } from './src/domain/techniquesInterdisciplinary.ts';
    import { HUMANITIES_BUILT_IN_TECHNIQUES } from './src/domain/techniquesHumanities.ts';
    import { CATALOG_BUILT_IN_TECHNIQUES, CATALOG_CLUSTERS } from './src/domain/techniquesCatalog.ts';
    import { techniqueFamily, techniqueCluster, TECHNIQUE_FAMILY_LABELS } from './src/domain/techniqueFamilies.ts';
    import * as metadata from './src/domain/techniqueCatalogMetadata.ts';
    import { SPECIFIC_CATALOG_WORKFLOW_COUNT, hasSpecificCatalogWorkflow } from './src/domain/techniquesCatalogWorkflows.ts';
    ${imports}
    const sourceGroups = [
      ['src/domain/techniquesExtended.ts', EXTENDED_BUILT_IN_TECHNIQUES],
      ['src/domain/techniquesInterdisciplinary.ts', INTERDISCIPLINARY_BUILT_IN_TECHNIQUES],
      ['src/domain/techniquesHumanities.ts', HUMANITIES_BUILT_IN_TECHNIQUES],
      ['src/domain/techniquesCatalog.ts', CATALOG_BUILT_IN_TECHNIQUES],
    ];
    const definitionPaths = new Map(sourceGroups.flatMap(([file, entries]) => entries.map(definition => [definition.id, file])));
    const workflowModules = [${workflowPaths.map((file, index) => `[${JSON.stringify(file)}, workflow${index}]`).join(',')}];
    const issues = metadata.techniqueCatalogReferenceIssues();
    if (issues.length) throw new Error('Unresolved upstream catalog references: ' + issues.join(', '));
    const techniques = BUILT_IN_TECHNIQUES.map(definition => {
      const definitionPath = definitionPaths.get(definition.id) || 'src/domain/techniques.ts';
      let workflowPath = definitionPath;
      const specific = definitionPath === 'src/domain/techniquesCatalog.ts' && hasSpecificCatalogWorkflow(definition.name);
      if (definitionPath === 'src/domain/techniquesCatalog.ts' && !specific) throw new Error('A catalog method has no specific workflow: ' + definition.name);
      if (specific) {
        workflowPath = 'src/domain/techniquesCatalogWorkflows.ts';
        for (const [file, namespace] of workflowModules) {
          if (file === 'src/domain/techniquesCatalogWorkflows.ts') continue;
          for (const [name, fn] of Object.entries(namespace)) if (/SpecificCatalogWorkflow$/.test(name) && !/^has/.test(name) && typeof fn === 'function') {
            const candidate = fn(definition.name);
            if (candidate && JSON.stringify(candidate) === JSON.stringify(definition.steps)) workflowPath = file;
          }
        }
      }
      return { definition, family: techniqueFamily(definition), cluster: techniqueCluster(definition), metadata: metadata.techniqueCatalogMetadata(definition), taskIds: metadata.techniqueTaskIds(definition), definitionPath, workflowPath, specificCatalogWorkflow: Boolean(specific) };
    });
    export const serialized = JSON.stringify({
      format: 1, source: ${JSON.stringify(CATALYST_SOURCE)},
      counts: { techniques: techniques.length, steps: techniques.reduce((sum, item) => sum + item.definition.steps.length, 0), catalogSpecificWorkflows: SPECIFIC_CATALOG_WORKFLOW_COUNT, catalogClusters: new Set(techniques.map(item => item.cluster)).size, declaredClusters: CATALOG_CLUSTERS.length },
      familyLabels: TECHNIQUE_FAMILY_LABELS, phases: metadata.TECHNIQUE_TASKS, clusters: CATALOG_CLUSTERS,
      playbooks: metadata.TECHNIQUE_PLAYBOOKS, retiredAliases: metadata.RETIRED_TECHNIQUE_ALIASES, referenceIssues: issues, techniques,
    });
  `;
  const root = new vm.SourceTextModule(rootSource, { context, identifier: 'materialize.mjs' });
  await root.link((specifier, referring) => {
    if (!specifier.startsWith('./')) fail(`unexpected source import: ${specifier}`);
    let key = path.posix.normalize(path.posix.join(path.posix.dirname(referring.identifier), specifier));
    if (!key.endsWith('.ts')) key += '.ts';
    if (!key.startsWith('src/domain/') || !pinned.files.has(key)) fail(`source import is outside the pinned catalog: ${key}`);
    if (!modules.has(key)) modules.set(key, new vm.SourceTextModule(stripTypeScriptTypes(pinned.files.get(key).toString('utf8'), { mode: 'strip', sourceUrl: key }), { context, identifier: key }));
    return modules.get(key);
  });
  await root.evaluate({ timeout: 5000 });
  if (typeof root.namespace.serialized !== 'string' || Buffer.byteLength(root.namespace.serialized) > 8 * 1024 * 1024) fail('materialized catalog exceeds its bounded JSON size.');
  const catalog = JSON.parse(root.namespace.serialized);
  if (catalog.counts.techniques !== 581 || catalog.counts.steps !== 2906 || catalog.counts.catalogSpecificWorkflows !== 486 || catalog.counts.catalogClusters !== 27 || catalog.counts.declaredClusters !== 26) fail(`the pinned catalog counts do not match the expected source definitions: ${JSON.stringify(catalog.counts)}.`);
  const ids = new Set(), names = new Set();
  for (const item of catalog.techniques) {
    if (ids.has(item.definition.id) || names.has(item.definition.name)) fail(`duplicate source method: ${item.definition.name}`);
    ids.add(item.definition.id); names.add(item.definition.name);
    item.sourceDefinitionSha256 = hash(JSON.stringify(item.definition));
    item.sourceRecordSha256 = hash(JSON.stringify(item));
  }
  return { catalog, bytes: Buffer.from(`${JSON.stringify(catalog, null, 2)}\n`) };
}

async function store(file, bytes) {
  await mkdir(path.dirname(file), { recursive: true });
  const temporary = `${file}.import-${process.pid}`;
  await writeFile(temporary, bytes, { flag: 'wx' });
  await rename(temporary, file);
}

export async function importCatalystCatalog({ source = path.join(CATALYST_VENDOR_DIR, 'upstream'), write = false } = {}) {
  const pinned = await readPinnedCatalystSource(path.resolve(source)), result = await materializeCatalystCatalog(pinned);
  const outputs = new Map([
    ['catalog.json', result.bytes], ['retrieval-manifest.json', pinned.manifestBytes],
    ['LICENSE.txt', pinned.files.get('LICENSE.txt')], ['LICENSES.md', pinned.files.get('LICENSES.md')],
    ['NOTICE.md', Buffer.from(CATALYST_NOTICE)],
    ['upstream/retrieval-manifest.json', pinned.manifestBytes],
    ...[...pinned.files].map(([file, bytes]) => [`upstream/${file}`, bytes]),
  ]);
  for (const [file, bytes] of outputs) {
    const destination = path.join(CATALYST_VENDOR_DIR, ...file.split('/'));
    if (write) await store(destination, bytes);
    else if (!(await normalFile(destination)).equals(bytes)) fail(`bundled output differs from the pinned import: ${file}`);
  }
  return { ...result.catalog.counts, sourceFiles: pinned.files.size, catalogBytes: result.bytes.length, catalogSha256: hash(result.bytes), sourceManifestSha256: CATALYST_SOURCE.retrievalManifestSha256, mode: write ? 'written' : 'verified' };
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2); let source, write = false;
  for (let index = 0; index < args.length; index++) {
    if (args[index] === '--source' && typeof args[index + 1] === 'string') source = args[++index];
    else if (args[index] === '--write') write = true;
    else if (args[index] !== '--check') fail(`unsupported option: ${args[index]}`);
  }
  try { process.stdout.write(`${JSON.stringify(await importCatalystCatalog({ source, write }), null, 2)}\n`); }
  catch (error) { process.stderr.write(`${error.message}\n`); process.exitCode = 1; }
}
