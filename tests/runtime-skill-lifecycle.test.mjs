import test from 'node:test';
import assert from 'node:assert/strict';
import {runtimeSkillsFixture,selectRuntimeSkill,expandRuntime,waitFor,deferred} from './fixture-runtime-skills.mjs';

test('Runtime preserves exact skill text, stale draft identity and an explicit discard',async t=>{
 const f=await runtimeSkillsFixture(t);
 await selectRuntimeSkill(f,f.alpha);
 assert.ok(f.calls.every(call=>call.method==='GET'),'browsing does not write');
 const exact='---\r\ndescription: Owner purpose\r\n---\r\n~~~text\r\n# Example heading\r\n~~~\r\n# Alpha fixture\r\n\r\nExact π instructions.\r\n';
 await f.input('#runtime-text',exact);
 await f.$('#runtime-editor').dispatch('submit');
 await waitFor(async()=> (await f.catalog.detail({id:f.alpha.id})).content===exact,'exact saved text');
 await waitFor(()=>f.$('#runtime-text').value===exact&&!f.$('#runtime-delete').disabled,'saved editor');
 const sent=f.calls.find(call=>call.method==='POST'&&call.route==='/api/skills/'+f.alpha.id);
 assert.deepEqual(sent.value,{expectedRevision:2,content:exact});
 const draft=exact+'Uncommitted draft.\r\n';
 await f.input('#runtime-text',draft);
 await selectRuntimeSkill(f,f.beta);
 f.ui.openSkillId(f.alpha.id);
 await waitFor(()=>f.$('#runtime-text').value===draft,'draft after navigation');
 const stored=await f.catalog.detail({id:f.alpha.id}),newer=await f.catalog.save({id:f.alpha.id,value:{expectedRevision:stored.revision,content:exact+'External revision.\r\n'}});
 await f.click('#runtime-refresh');
 await waitFor(()=>f.$('#runtime-text').value===draft&&!f.$('#runtime-save').disabled,'draft after refresh');
 await f.$('#runtime-editor').dispatch('submit');
 await waitFor(()=>f.$('#runtime-save-status').textContent.includes('Skill changed'),'stale save conflict');
 assert.equal((await f.catalog.detail({id:f.alpha.id})).content,newer.content);
 assert.equal(f.$('#runtime-text').value,draft);
 await f.click('#runtime-discard');
 await waitFor(()=>f.$('#runtime-text').value===newer.content,'discard loads current saved text');
 assert.equal(f.$('#runtime-save').disabled,true);
});

test('Runtime creation prevents duplicate submits, retains failures and starts a fresh next draft',async t=>{
 const f=await runtimeSkillsFixture(t),gate=deferred();let hold=true;
 f.setHook(async call=>{if(hold&&call.route==='/api/skills'&&call.method==='POST'){hold=false;await gate.promise;}});
 await f.click('#runtime-add');f.$('#runtime-new-kind').value='skill';
 const title='Created fixture',content='# Created fixture\r\n\r\nExact new instructions.\r\n';
 await f.input('#runtime-new-title',title);await f.input('#runtime-new-text',content);
 const form=f.$('#runtime-new-form'),first=form.dispatch('submit');
 await waitFor(()=>f.calls.some(call=>call.method==='POST'&&call.route==='/api/skills'),'create admitted');
 await form.dispatch('submit');
 assert.equal(f.calls.filter(call=>call.method==='POST'&&call.route==='/api/skills').length,1);
 gate.resolve();await first;
 await waitFor(()=>f.$('#runtime-text').value===content,'new skill selected');
 const created=(await f.catalog.list({source:'user'})).entries.find(row=>row.title===title);
 assert.ok(created);assert.equal((await f.catalog.detail({id:created.id})).content,content);
 await f.click('#runtime-add');
 assert.equal(f.$('#runtime-new-title').value,'','a completed creation does not seed another accidental copy');
 assert.equal(f.$('#runtime-new-text').value,'');
 f.$('#runtime-new-kind').value='skill';
 await f.input('#runtime-new-title','Failed creation');await f.input('#runtime-new-text','Keep this unsaved creation.');
 f.setHook(call=>{if(call.route==='/api/skills'&&call.method==='POST')throw Error('Fixture create failure');});
 await f.$('#runtime-new-form').dispatch('submit');
 await waitFor(()=>f.$('#runtime-status').textContent.includes('Fixture create failure'));
 assert.equal(f.$('#runtime-new-title').value,'Failed creation');
 assert.equal(f.$('#runtime-new-text').value,'Keep this unsaved creation.');
 assert.equal(f.$('#runtime-new-form').hidden,false);
 assert.ok(!(await f.catalog.list({source:'user'})).entries.some(row=>row.title==='Failed creation'));
 await f.click('#runtime-new-cancel');
 await waitFor(()=>f.$('#runtime-new-form').hidden&&!f.$('#runtime-editor').hidden,'cancel returns to editor');
});

test('Runtime in-flight saves submit once and honor the latest queued selection',async t=>{
 const f=await runtimeSkillsFixture(t),gate=deferred();let held=false;
 await selectRuntimeSkill(f,f.alpha);
 f.setHook(async call=>{if(call.route==='/api/skills/'+f.alpha.id&&call.method==='POST'){held=true;await gate.promise;}});
 const body='# Alpha fixture\n\nOne exact committed change.\n';
 await f.input('#runtime-text',body);await f.$('#runtime-editor').dispatch('submit');
 await waitFor(()=>held,'save paused in API');
 await f.$('#runtime-editor').dispatch('submit');
 f.ui.openSkillId(f.beta.id);
 assert.equal(f.calls.filter(call=>call.route==='/api/skills/'+f.alpha.id&&call.method==='POST').length,1);
 assert.equal(f.$('#runtime-text').value,body);
 gate.resolve();
 await waitFor(()=>f.$('#runtime-heading').textContent===f.beta.title&&f.$('#runtime-text').value===f.beta.content,'queued selection after save');
 assert.equal((await f.catalog.detail({id:f.alpha.id})).content,body);
 assert.equal((await f.catalog.detail({id:f.beta.id})).content,f.beta.content);
});

test('Runtime delete confirmation, conflicts and restore preserve exact owner content',async t=>{
 const f=await runtimeSkillsFixture(t);
 await selectRuntimeSkill(f,f.alpha);
 const draft=f.alpha.content+'Unsaved owner draft.\n';
 await f.input('#runtime-text',draft);await f.click('#runtime-delete');
 assert.equal(f.$('#runtime-delete-confirm').hidden,false);
 await f.click('#runtime-delete-cancel');
 assert.equal(f.$('#runtime-text').value,draft);
 assert.equal(f.calls.filter(call=>call.method==='DELETE').length,0);
 const newer=await f.catalog.save({id:f.alpha.id,value:{expectedRevision:f.alpha.revision,content:'# Alpha fixture\r\n\r\nNewer exact saved text π.\r\n'}});
 const gate=deferred();let held=false;
 f.setHook(async call=>{if(call.route==='/api/skills/'+f.alpha.id&&call.method==='DELETE'){held=true;await gate.promise;}});
 await f.click('#runtime-delete');await f.click('#runtime-delete-yes');
 await waitFor(()=>held,'delete paused');
 await f.click('#runtime-delete-yes');
 assert.equal(f.calls.filter(call=>call.method==='DELETE').length,1);
 gate.resolve();
 await waitFor(()=>f.$('#runtime-status').textContent.includes('Skill changed'),'delete conflict');
 assert.equal(f.$('#runtime-text').value,draft);
 assert.equal((await f.catalog.detail({id:f.alpha.id})).content,newer.content);
 f.setHook(null);
 await f.click('#runtime-discard');
 await waitFor(()=>f.$('#runtime-text').value===newer.content,'discard stale deletion draft');
 await f.click('#runtime-delete');await f.click('#runtime-delete-yes');
 await waitFor(()=>f.$('#runtime-status').textContent.includes('Runtime item changed'),'delete committed');
 await assert.rejects(f.catalog.detail({id:f.alpha.id}),{status:404});
 await expandRuntime(f,'runtime:deleted');
 await f.click('[data-runtime-item="deleted:'+f.alpha.id+'"]');
 await waitFor(()=>!f.$('#runtime-restore').disabled,'restore available');
 await f.click('#runtime-restore');
 await waitFor(async()=>{try{return (await f.catalog.detail({id:f.alpha.id})).content===newer.content;}catch{return false;}},'exact owner restore');
 assert.equal((await f.catalog.detail({id:f.beta.id})).content,f.beta.content);
});

test('Runtime ignores late detail responses after leaving, reentering and destroying',async t=>{
 const f=await runtimeSkillsFixture(t),first=deferred();let held=false;
 f.setHook(call=>{if(!held&&call.method==='GET'&&call.route==='/api/skills/'+f.alpha.id){held=true;return first.promise;}});
 await f.input('#runtime-search',f.alpha.title);
 await f.click('[data-runtime-item="skill:'+f.alpha.id+'"]');
 await waitFor(()=>held,'detail read paused');
 f.ui.leave();f.ui.enter();
 await waitFor(()=>f.$('#runtime-text').value===f.alpha.content,'reentered current source');
 first.resolve({...f.alpha,revision:999,content:'# Late incorrect response\n'});
 await new Promise(resolve=>setTimeout(resolve,10));
 assert.equal(f.$('#runtime-text').value,f.alpha.content);
 const last=deferred();let secondHeld=false;
 f.setHook(call=>{if(call.method==='GET'&&call.route==='/api/skills/'+f.beta.id){secondHeld=true;return last.promise;}});
 await f.input('#runtime-search',f.beta.title);
 await f.click('[data-runtime-item="skill:'+f.beta.id+'"]');
 await waitFor(()=>secondHeld,'second detail paused');
 f.ui.destroy();last.resolve(f.beta);
 await new Promise(resolve=>setTimeout(resolve,10));
 assert.equal(f.mount.children.length,0);
 assert.ok(f.calls.every(call=>call.method==='GET'));
});
